//! Windows Loopback backend: WASAPI loopback capture (ADR-0001 route).
//!
//! Opens the render endpoint (output device) in shared mode with
//! `AUDCLNT_STREAMFLAGS_LOOPBACK` and drains its capture packets on a
//! dedicated thread (all COM confined there — the UI thread may have a
//! different apartment model). Audio arrives in the device's mix format and
//! is normalized through the shared `FeedCtx`.

use std::sync::Arc;
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::mpsc;
use std::thread::{self, JoinHandle};
use std::time::Duration;

use windows::Win32::Devices::FunctionDiscovery::PKEY_Device_FriendlyName;
use windows::Win32::Media::Audio::{
    AUDCLNT_BUFFERFLAGS_SILENT, AUDCLNT_SHAREMODE_SHARED, AUDCLNT_STREAMFLAGS_LOOPBACK,
    DEVICE_STATE_ACTIVE, IAudioCaptureClient, IAudioClient, IMMDevice, IMMDeviceEnumerator,
    eConsole, eRender,
};
use windows::Win32::System::Com::StructuredStorage::{PROPVARIANT, PROPVARIANT_0_0};
use windows::Win32::System::Com::{
    CLSCTX_ALL, COINIT_MULTITHREADED, CoCreateInstance, CoInitializeEx, CoTaskMemFree,
    CoUninitialize, STGM_READ,
};
use windows::core::{GUID, PWSTR};

use crate::{CaptureError, CaptureStream, DeviceInfo, FeedCtx, SourceKind, StreamHolder};

/// Shown when the backend cannot run (rare: COM/endpoint issues).
pub(crate) const NOTE: &str = "Loopback 不可用:WASAPI 初始化失败";

/// `CLSID_MMDeviceEnumerator` {BCD039FE-BFD8-4C32-97D0-5E2B0B2D0A4C} is not
/// generated by the windows crate; declared here per the WASABI docs.
const CLSID_MM_DEVICE_ENUMERATOR: GUID = GUID::from_u128(0xbc_d039fe_bfd8_4c32_97d0_5e2b0b2d0a4c);

/// VT_LPWSTR tag of a PROPVARIANT carrying a string.
const VT_LPWSTR: u16 = 31;

const SETUP_TIMEOUT: Duration = Duration::from_secs(5);
/// Capture poll period; the mix-format buffer absorbs the jitter.
const POLL_INTERVAL: Duration = Duration::from_millis(10);

/// Enumerates active render endpoints as Loopback Sources.
pub(crate) fn list_loopback_devices() -> Vec<DeviceInfo> {
    with_com_thread(|| -> windows::core::Result<Vec<DeviceInfo>> {
        let enumerator: IMMDeviceEnumerator = make_enumerator()?;
        let collection = unsafe { enumerator.EnumAudioEndpoints(eRender, DEVICE_STATE_ACTIVE) }?;
        let mut devices = Vec::new();
        let count = unsafe { collection.GetCount() }.unwrap_or(0);
        for i in 0..count {
            if let Ok(device) = unsafe { collection.Item(i) } {
                if let Some(info) = endpoint_info(&device) {
                    devices.push(info);
                }
            }
        }
        Ok(devices)
    })
    .and_then(|r| r.ok())
    .unwrap_or_default()
}

pub(crate) fn default_device() -> Option<DeviceInfo> {
    with_com_thread(|| {
        let enumerator: IMMDeviceEnumerator = make_enumerator().ok()?;
        let device: IMMDevice =
            unsafe { enumerator.GetDefaultAudioEndpoint(eRender, eConsole) }.ok()?;
        endpoint_info(&device)
    })
    .flatten()
}

pub(crate) fn open_loopback(source: &DeviceInfo) -> Result<CaptureStream, CaptureError> {
    let (prod, cons) = crate::split_ring();
    let dead = Arc::new(AtomicBool::new(false));
    let stop = Arc::new(AtomicBool::new(false));
    let (tx, rx) = mpsc::channel::<Result<(), String>>();

    let id = source.id.clone();
    let stop_thread = stop.clone();
    let dead_thread = dead.clone();

    let thread = thread::Builder::new()
        .name("audio-spectrum-wasapi-loopback".into())
        .spawn(move || {
            let result = run_loopback_thread(&id, prod, &stop_thread, &dead_thread);
            let _ = tx.send(result);
        })
        .map_err(|e| CaptureError::OpenFailed(format!("无法启动采集线程:{e}")))?;

    match rx.recv_timeout(SETUP_TIMEOUT) {
        Ok(Ok(())) => Ok(CaptureStream::new(
            StreamHolder::Wasapi(WasapiSession {
                thread: Some(thread),
                stop,
            }),
            cons,
            dead,
        )),
        Ok(Err(msg)) => {
            stop.store(true, Ordering::Relaxed);
            let _ = thread.join();
            Err(CaptureError::OpenFailed(msg))
        }
        Err(_) => {
            stop.store(true, Ordering::Relaxed);
            let _ = thread.join();
            Err(CaptureError::OpenFailed("WASAPI 初始化超时".into()))
        }
    }
}

/// Runs on the capture thread: owns all COM state for the stream lifetime.
fn run_loopback_thread(
    id: &str,
    prod: crate::HeapProd<f32>,
    stop: &AtomicBool,
    dead: &AtomicBool,
) -> Result<(), String> {
    unsafe { CoInitializeEx(None, COINIT_MULTITHREADED) }
        .ok()
        .map_err(|e| format!("CoInitializeEx 失败:{e}"))?;

    // Ensure CoUninitialize on every path.
    let result = capture_loop(id, prod, stop, dead);
    unsafe { CoUninitialize() };
    result
}

fn capture_loop(
    id: &str,
    prod: crate::HeapProd<f32>,
    stop: &AtomicBool,
    dead: &AtomicBool,
) -> Result<(), String> {
    unsafe {
        let enumerator: IMMDeviceEnumerator =
            CoCreateInstance(&CLSID_MM_DEVICE_ENUMERATOR, None, CLSCTX_ALL)
                .map_err(|e| format!("创建设备枚举器失败:{e}"))?;

        // Resolve the endpoint by id (fall back to the default render device,
        // which surfaces as a device change through the Reconnect flow).
        let device: IMMDevice = match enumerator.GetDevice(&windows::core::HSTRING::from(id)) {
            Ok(d) => d,
            Err(_) => enumerator
                .GetDefaultAudioEndpoint(eRender, eConsole)
                .map_err(|e| format!("目标设备已断开，且无默认输出设备:{e}"))?,
        };

        let client: IAudioClient = device
            .Activate(CLSCTX_ALL, None)
            .map_err(|e| format!("IAudioClient 激活失败:{e}"))?;

        let format_ptr = client
            .GetMixFormat()
            .map_err(|e| format!("GetMixFormat 失败:{e}"))?;
        if format_ptr.is_null() {
            return Err("GetMixFormat 返回空格式".into());
        }
        let format = &*format_ptr;

        client
            .Initialize(
                AUDCLNT_SHAREMODE_SHARED,
                AUDCLNT_STREAMFLAGS_LOOPBACK,
                0, // default buffer duration
                0,
                format_ptr,
                None,
            )
            .map_err(|e| format!("WASAPI loopback Initialize 失败:{e}"))?;

        let channels = format.nChannels as usize;
        let sample_format = decode_format(format.wFormatTag, format.wBitsPerSample);

        let capture: IAudioCaptureClient = client
            .GetService()
            .map_err(|e| format!("GetService(IAudioCaptureClient) 失败:{e}"))?;

        client.Start().map_err(|e| format!("流启动失败:{e}"))?;
        CoTaskMemFree(Some(format_ptr as *const core::ffi::c_void));

        let mut feed = FeedCtx::new(prod, format.nSamplesPerSec, channels);

        while !stop.load(Ordering::Relaxed) {
            thread::sleep(POLL_INTERVAL);
            let mut packet_frames = match capture.GetNextPacketSize() {
                Ok(n) => n,
                Err(_) => {
                    dead.store(true, Ordering::Relaxed);
                    break;
                }
            };
            while packet_frames > 0 {
                let mut data = std::ptr::null_mut::<u8>();
                let mut frames = 0u32;
                let mut flags = 0u32;
                if capture
                    .GetBuffer(&mut data, &mut frames, &mut flags, None, None)
                    .is_err()
                {
                    dead.store(true, Ordering::Relaxed);
                    break;
                }
                if flags & AUDCLNT_BUFFERFLAGS_SILENT.0 as u32 != 0 {
                    for _ in 0..frames as usize * channels {
                        feed.push_sample(0.0);
                    }
                } else if !data.is_null() {
                    push_frames(&mut feed, data, frames as usize, channels, sample_format);
                }
                if capture.ReleaseBuffer(frames).is_err() {
                    dead.store(true, Ordering::Relaxed);
                    break;
                }
                match capture.GetNextPacketSize() {
                    Ok(n) => packet_frames = n,
                    Err(_) => {
                        dead.store(true, Ordering::Relaxed);
                        break;
                    }
                }
            }
        }

        let _ = client.Stop();
        Ok(())
    }
}

#[derive(Clone, Copy, PartialEq)]
enum MixFormat {
    F32,
    I16,
    I32,
    Unsupported,
}

fn decode_format(tag: u16, bits: u16) -> MixFormat {
    const WAVE_FORMAT_PCM: u16 = 1;
    const WAVE_FORMAT_IEEE_FLOAT: u16 = 3;
    const WAVE_FORMAT_EXTENSIBLE: u16 = 0xFFFE;
    match (tag, bits) {
        (WAVE_FORMAT_IEEE_FLOAT, 32) => MixFormat::F32,
        (WAVE_FORMAT_PCM, 16) => MixFormat::I16,
        (WAVE_FORMAT_PCM, 32) => MixFormat::I32,
        // Extensible carries the real tag in the SubFormat GUID; shared-mode
        // mix formats are float32 in practice, 16-bit PCM otherwise.
        (WAVE_FORMAT_EXTENSIBLE, 32) => MixFormat::F32,
        (WAVE_FORMAT_EXTENSIBLE, 16) => MixFormat::I16,
        _ => MixFormat::Unsupported,
    }
}

/// Conversion + mixdown happen inside `FeedCtx`; this just widens samples.
/// Runs on the capture thread: no allocation.
fn push_frames(
    feed: &mut FeedCtx,
    data: *const u8,
    frames: usize,
    channels: usize,
    fmt: MixFormat,
) {
    let count = frames * channels;
    match fmt {
        MixFormat::F32 => unsafe {
            let samples = std::slice::from_raw_parts(data as *const f32, count);
            feed.push_samples(samples.iter().copied());
        },
        MixFormat::I16 => unsafe {
            let samples = std::slice::from_raw_parts(data as *const i16, count);
            feed.push_samples(samples.iter().map(|&x| x as f32 / 32768.0));
        },
        MixFormat::I32 => unsafe {
            let samples = std::slice::from_raw_parts(data as *const i32, count);
            feed.push_samples(samples.iter().map(|&x| x as f32 / 2147483648.0));
        },
        MixFormat::Unsupported => {}
    }
}

// ---------------------------------------------------------------------------
// Device enumeration helpers (run on a short-lived COM thread)
// ---------------------------------------------------------------------------

fn make_enumerator() -> windows::core::Result<IMMDeviceEnumerator> {
    unsafe { CoCreateInstance(&CLSID_MM_DEVICE_ENUMERATOR, None, CLSCTX_ALL) }
}

fn endpoint_info(device: &IMMDevice) -> Option<DeviceInfo> {
    unsafe {
        let id_pwstr: PWSTR = device.GetId().ok()?;
        let id = id_pwstr.to_string().ok()?;
        // The PWSTR from GetId is CoTaskMem-allocated.
        CoTaskMemFree(Some(id_pwstr.as_ptr() as *const core::ffi::c_void));

        let name = device
            .OpenPropertyStore(STGM_READ)
            .and_then(|store| {
                let value = store.GetValue(&PKEY_Device_FriendlyName)?;
                let name = propvariant_string(&value)
                    .or_else(|| Some(id.clone()))
                    .unwrap_or_else(|| "音频输出设备".into());
                Ok(name)
            })
            .unwrap_or_else(|_: windows::core::Error| "音频输出设备".into());

        Some(DeviceInfo {
            kind: SourceKind::Loopback,
            id,
            name,
        })
    }
}

/// Reads a VT_LPWSTR PROPVARIANT (device friendly names).
fn propvariant_string(value: &PROPVARIANT) -> Option<String> {
    unsafe {
        // The variant layout: Anonymous.Anonymous { vt, …, Anonymous.pwszVal }.
        let inner = &value.Anonymous.Anonymous;
        if inner.vt.0 != VT_LPWSTR {
            return None;
        }
        let inner: &PROPVARIANT_0_0 = inner;
        let pwstr: PWSTR = inner.Anonymous.pwszVal;
        pwstr.to_string().ok()
    }
}

/// COM is apartment-sensitive: enumeration runs on a throwaway thread with
/// its own MTA so the caller's apartment is never disturbed.
fn with_com_thread<T: Send + 'static>(f: impl FnOnce() -> T + Send + 'static) -> Option<T> {
    thread::spawn(move || -> Option<T> {
        if unsafe { CoInitializeEx(None, COINIT_MULTITHREADED) }.is_err() {
            return None;
        }
        let result = f();
        unsafe { CoUninitialize() };
        Some(result)
    })
    .join()
    .ok()
    .flatten()
}

/// Keeps the WASAPI thread running; dropping it stops the capture.
pub(crate) struct WasapiSession {
    thread: Option<JoinHandle<()>>,
    stop: Arc<AtomicBool>,
}

impl Drop for WasapiSession {
    fn drop(&mut self) {
        self.stop.store(true, Ordering::Relaxed);
        if let Some(thread) = self.thread.take() {
            let _ = thread.join();
        }
    }
}
